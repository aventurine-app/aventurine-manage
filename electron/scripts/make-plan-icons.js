'use strict';

// Writes static/js/plan/icon-data.js: the Phosphor icons the Plan section
// draws (every module icon in its catalog, and the chrome icons below), as
// inline SVG markup. Run by hand from electron/ after adding an icon to the
// catalog or to UI_ICONS, and commit the result. The app never fetches an icon.
//
//   node scripts/make-plan-icons.js
//
// Every icon is the regular weight, with no fill layer. Phosphor Icons are MIT licensed
// (https://phosphoricons.com); the license travels in the generated header.

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const Catalog = require(path.join(REPO_ROOT, 'static', 'js', 'plan', 'sim', 'catalog.js'));

const ASSETS = path.join(__dirname, '..', 'node_modules', '@phosphor-icons', 'core', 'assets');
const OUT = path.join(REPO_ROOT, 'static', 'js', 'plan', 'icon-data.js');

// Chrome icons, by Phosphor name.
const UI_ICONS = [
    'plus', 'minus', 'x', 'trash', 'copy', 'magnifying-glass', 'caret-down', 'caret-right',
    'caret-left', 'caret-up', 'arrow-counter-clockwise', 'arrow-clockwise', 'corners-out',
    'gear-six', 'folder', 'export', 'download-simple', 'lock-key', 'warning', 'warning-circle',
    'info', 'check', 'check-circle', 'dots-three', 'pencil-simple', 'arrow-right', 'chart-line',
    'chart-bar', 'table', 'sidebar-simple', 'flow-arrow', 'calendar-blank',
    'sparkle', 'chart-line-up', 'squares-four', 'clock-counter-clockwise', 'shield-check', 'user-circle',
    // The navigation: Plans and each plan, Goals, Compare (Analyze is chart-line-up).
    'files', 'file', 'target', 'scales',
    // A goal's rule: its comparison and deadline (the measures wear module icons),
    // and its card's colour.
    'greater-than-or-equal', 'less-than-or-equal', 'palette',
    // The handle a goal is dragged by to reorder the list.
    'dots-six-vertical',
    // Status tags and progress (met, missed, not measured), Compare's swap and
    // its differences up or down.
    'x-circle', 'minus-circle', 'arrows-left-right', 'arrow-up', 'arrow-down',
    // Export: the PDF report, the spreadsheet, the plan file and Download All.
    'file-pdf', 'file-csv', 'file-code', 'file-zip',
    // The person's age: the canvas's time tag and a goal due by an age.
    'user',
    // The inspector's icon for a modifier (inspector.js ROLE_ICON).
    'sliders-horizontal',
];

// Each asset is one <svg> of <path d="…"/> elements. Anything
// else means Phosphor changed shape and this script needs a look, so fail.
const SVG_RE = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 256 256" fill="currentColor">((?:<path d="[-0-9.,A-Za-z ]+"\/>)+)<\/svg>\s*$/;

function inner(name) {
    const file = path.join(ASSETS, 'regular', `${name}.svg`);
    const svg = fs.readFileSync(file, 'utf8');
    const m = SVG_RE.exec(svg);
    if (!m) throw new Error(`unexpected markup in ${path.basename(file)}`);
    return m[1];
}

function main() {
    const moduleIcons = new Set([
        ...Catalog.PRESETS.map((p) => p.icon),
        ...Catalog.CATEGORIES.flatMap((c) => [c.icon, ...c.icons]),
    ]);
    const regular = {};
    for (const name of [...new Set([...moduleIcons, ...UI_ICONS])].sort()) regular[name] = inner(name);

    const header = [
        "'use strict';",
        '',
        '// GENERATED by electron/scripts/make-plan-icons.js. Do not edit by hand.',
        '//',
        '// Phosphor Icons, https://phosphoricons.com. MIT License,',
        '// Copyright (c) 2020 Phosphor Icons. Inner SVG markup on a 256 viewBox;',
        '// plan/icons.js wraps it.',
        '',
    ].join('\n');
    const body = `window.PLAN_ICON_DATA = ${JSON.stringify({ regular }, null, 1)};\n`;
    fs.writeFileSync(OUT, header + body);
    console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(regular).length} icons`);
}

main();
